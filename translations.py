def messages(props_class):
    """The {"ru_RU": {(context, English): Russian}} table for bpy.app.translations."""
    ru = {}
    for prop in props_class.bl_rna.properties:
        pair = PROPERTIES.get(prop.identifier)
        if pair is None:
            continue
        ru[("*", prop.name)] = pair[0]
        if prop.description:
            ru[("*", prop.description)] = pair[1]
        if prop.type == "ENUM":
            for item in prop.enum_items:
                found = ENUM_ITEMS.get(prop.identifier, {}).get(item.identifier)
                if found is not None:
                    ru[("*", item.name)] = found[0]
                    if item.description:
                        ru[("*", item.description)] = found[1]
    for english, russian in LABELS.items():
        ru[("*", english)] = russian
        ru[("Operator", english)] = russian
    return {"ru_RU": ru}


def register(props_class):
    global _registered
    unregister()
    bpy.app.translations.register(__name__, messages(props_class))
    _registered = True


def unregister():
    global _registered
    if _registered:
        try:
            bpy.app.translations.unregister(__name__)
        except (ValueError, RuntimeError):
            pass
        _registered = False
